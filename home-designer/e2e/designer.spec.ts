test('room editing, pointer drag, rotation, history, export/import, persistence and 3D',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.addInitScript(()=>{if(!localStorage.getItem('design-c-home-v1'))localStorage.setItem('design-c-home-v1','{"version":1,"items":[]}')})
  await page.goto('/')
  await page.getByRole('button',{name:'Master bedroom, 14 by 16 feet',exact:true}).click()
  await page.getByRole('button',{name:'+ Bed',exact:true}).click()
  const bed=page.getByRole('button',{name:'Bed, 6 by 6.5 feet',exact:true})
  const before=await page.getByRole('spinbutton',{name:'x',exact:true}).inputValue()
  const box=(await bed.boundingBox())!
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
  await page.mouse.down()
  await page.mouse.move(box.x+box.width/2+45,box.y+box.height/2+20,{steps:8})
  await page.mouse.up()
  await expect(page.getByRole('spinbutton',{name:'x',exact:true})).not.toHaveValue(before)
  await page.getByRole('button',{name:'Rotate +15°',exact:true}).click()
  await expect(page.getByRole('spinbutton',{name:'rotation',exact:true})).toHaveValue('15')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await bed.click()
  await expect(page.getByRole('spinbutton',{name:'rotation',exact:true})).toHaveValue('0')
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await bed.click()
  await expect(page.getByRole('spinbutton',{name:'rotation',exact:true})).toHaveValue('15')
  await page.getByRole('button',{name:'north wall',exact:true}).click()
  await page.getByRole('button',{name:'+ Cabinet',exact:true}).click()
  await page.getByRole('button',{name:'Ceiling',exact:true}).click()
  await page.getByRole('button',{name:'+ Fan',exact:true}).click()
  await page.getByRole('button',{name:'+ Light',exact:true}).click()
  const saved=await page.evaluate(()=>localStorage.getItem('design-c-home-v1')!)
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export design',exact:true}).click()
  const stream=await (await download).createReadStream()
  const chunks:Buffer[]=[]
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  expect(JSON.parse(Buffer.concat(chunks).toString())).toEqual(JSON.parse(saved))
  await page.locator('input[type=file]').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"version":99,"items":[]}')})
  await expect(page.getByRole('alert')).toContainText('Import rejected')
  expect(await page.evaluate(()=>localStorage.getItem('design-c-home-v1'))).toBe(saved)
  await page.locator('input[type=file]').setInputFiles({name:'design.json',mimeType:'application/json',buffer:Buffer.from(saved)})
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button',{name:'Master bedroom, 14 by 16 feet',exact:true}).click()
  await expect(page.getByRole('heading',{name:'In this room (4)'})).toBeVisible()
  await page.getByRole('button',{name:'3D preview',exact:true}).click()
  await expect(page.locator('.three-view canvas')).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.locator('.three-view canvas').screenshot({path:'test-results/room-3d.png'})
  expect(errors).toEqual([])
})

