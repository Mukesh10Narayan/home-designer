test('whole-house 3D wall selection, visibility and independent day/night lighting',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button',{name:'Whole house 3D',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Whole house 3D'})
  const model=dialog.locator('.three-view')
  await expect(model.locator('canvas')).toBeVisible()
  await expect(model).toHaveAttribute('data-active-lights','28')
  await expect(model).toHaveAttribute('data-sun-rays','true')
  const canvas=model.locator('canvas')
  const rect=(await canvas.boundingBox())!
  const camera=new PerspectiveCamera(45,rect.width/rect.height,.1,400)
  camera.position.set(65,65,84)
  camera.lookAt(13.5,1.5,26.5)
  camera.updateMatrixWorld()
  const projected=new Vector3(5,8,52.965).project(camera)
  await page.mouse.click(rect.x+(projected.x+1)*rect.width/2,rect.y+(1-projected.y)*rect.height/2)
  await expect(dialog.getByRole('heading',{name:'Master bedroom · south wall',exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'Show all objects',exact:true}).click()
  await dialog.getByRole('button',{name:'Night',exact:true}).click()
  await expect(model).toHaveAttribute('data-sun-rays','false')
  await expect(dialog.getByRole('checkbox',{name:'Sunlight',exact:true})).toBeDisabled()
  await dialog.getByRole('checkbox',{name:'Ceiling / tube lights',exact:true}).uncheck()
  await expect(model).toHaveAttribute('data-active-lights','0')
  await dialog.getByRole('button',{name:'Day',exact:true}).click()
  await expect(model).toHaveAttribute('data-sun-rays','true')
  await expect(model).toHaveAttribute('data-active-lights','0')
  await dialog.getByRole('checkbox',{name:'Ceiling / tube lights',exact:true}).check()
  await dialog.getByRole('checkbox',{name:'Show Ceiling light starter-master-0',exact:true}).uncheck()
  await expect(model).toHaveAttribute('data-active-lights','27')
  await dialog.getByRole('button',{name:'Inspect east wall',exact:true}).click()
  await expect(dialog.getByRole('heading',{name:'Master bedroom · east wall',exact:true})).toBeVisible()
  await expect(dialog.getByRole('region',{name:'Selected wall details'})).toContainText('#b1bdb5')
  await expect(dialog.getByRole('checkbox',{name:'Show Wardrobe starter-master-3',exact:true})).toBeChecked()
  const count=Number(await model.getAttribute('data-visible-items'))
  await dialog.getByRole('checkbox',{name:'Show Wardrobe starter-master-3',exact:true}).uncheck()
  await expect(model).toHaveAttribute('data-visible-items',String(count-1))
  await model.locator('canvas').screenshot({path:'test-results/whole-house-day.png'})
  await dialog.getByRole('button',{name:'Night',exact:true}).click()
  await model.locator('canvas').screenshot({path:'test-results/whole-house-night.png'})
  await dialog.getByRole('button',{name:'Open wall editor',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button',{name:'east wall',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('heading',{name:'Master bedroom',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})

